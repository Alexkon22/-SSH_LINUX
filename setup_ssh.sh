#!/bin/bash

# ==============================================
# Настройка SSH-доступа
# ==============================================

# Замените на ваши публичные SSH-ключи
# Можно добавить несколько ключей через пробел
PUBLIC_KEYS=(
    "ssh-ed25519 AAAAC... ваш_ключ_1"
    "ssh-ed25519 AAAAC... ваш_ключ_2"
    # Добавьте свои ключи выше
)

# ==============================================
# 1. Добавление ключей для root
# ==============================================

echo "=== Настройка SSH для root ==="

# Создаём папку .ssh для root (если её нет)
mkdir -p /root/.ssh
chmod 700 /root/.ssh

# Добавляем публичные ключи
for key in "${PUBLIC_KEYS[@]}"; do
    echo "$key" >> /root/.ssh/authorized_keys
done

chmod 600 /root/.ssh/authorized_keys

# ---------- ПРОВЕРКА ДЛЯ ROOT ----------
echo "=== Проверка для root ==="
# 1) Проверяем, что папка существует и имеет правильные права (drwx------)
ls -ld /root/.ssh
# 2) Проверяем содержимое файла authorized_keys
cat /root/.ssh/authorized_keys
# 3) Проверяем права самого файла (-rw-------)
ls -la /root/.ssh/authorized_keys

# ==============================================
# 2. Добавление ключей для alex
# ==============================================

echo "=== Настройка SSH для alex ==="

# Создаём папку .ssh для alex
mkdir -p /home/alex/.ssh
chmod 700 /home/alex/.ssh

# Добавляем публичные ключи
for key in "${PUBLIC_KEYS[@]}"; do
    echo "$key" >> /home/alex/.ssh/authorized_keys
done

chmod 600 /home/alex/.ssh/authorized_keys

# Убедимся, что владелец – alex
chown -R alex:alex /home/alex/.ssh

# ---------- ПРОВЕРКА ДЛЯ ALEX ----------
echo "=== Проверка для alex ==="
# 1) Проверяем папку
ls -ld /home/alex/.ssh
# 2) Проверяем содержимое файла
cat /home/alex/.ssh/authorized_keys
# 3) Проверяем права и владельца
ls -la /home/alex/.ssh/authorized_keys

# ==============================================
# 3. Дополнительная проверка – пользователи
# ==============================================

echo "=== Существование пользователей ==="
id root
id alex

# ==============================================
# 4. Проверка возможности входа по ключу
# ==============================================

echo "=== Для проверки подключения выполните в НОВОМ терминале: ==="
echo ""
echo "ssh -i /путь/к/приватному_ключу root@$(hostname -I | awk '{print $1}')"
echo "ssh -i /путь/к/приватному_ключу alex@$(hostname -I | awk '{print $1}')"
echo ""
echo "=== Настройка завершена ==="
